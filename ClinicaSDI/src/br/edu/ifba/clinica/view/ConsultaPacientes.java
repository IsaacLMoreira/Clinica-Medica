    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linhaSelecionada = tblPacientes.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um paciente para excluir."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir este paciente?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {

            int codigo = Integer.parseInt(
                    tblPacientes.getValueAt(linhaSelecionada, 0).toString()
            );

            PacienteRepository repository = new PacienteRepository();

            repository.excluir(codigo);

            JOptionPane.showMessageDialog(
                    this,
                    "Paciente excluído com sucesso!"
            );

            carregarPacientes();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao excluir paciente:\n" + e.getMessage()
            );

            e.printStackTrace();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        
        int linhaSelecionada = tblPacientes.getSelectedRow();

        if (linhaSelecionada == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um paciente para alterar."
            );

            return;
        }

        try {

            Paciente paciente = new Paciente();

            paciente.setCodigo(
                    Integer.parseInt(
                            tblPacientes.getValueAt(
                                    linhaSelecionada,
                                    0
                            ).toString()
                    )
            );

            paciente.setNome(
                    tblPacientes.getValueAt(
                            linhaSelecionada,
                            1
                    ).toString()
            );

            paciente.setCpf(
                    tblPacientes.getValueAt(
                            linhaSelecionada,
                            2
                    ).toString()
            );

            DateTimeFormatter formato =
                    DateTimeFormatter.ofPattern("dd/MM/yyyy");

            paciente.setDataNascimento(
                    LocalDate.parse(
                            tblPacientes.getValueAt(
                                    linhaSelecionada,
                                    3
                            ).toString(),
                            formato
                    )
            );

            paciente.setTelefone(
                    tblPacientes.getValueAt(
                            linhaSelecionada,
                            4
                    ).toString()
            );

            paciente.setEmail(
                    tblPacientes.getValueAt(
                            linhaSelecionada,
                            5
                    ).toString()
            );

            paciente.setConvenio(
                    tblPacientes.getValueAt(
                            linhaSelecionada,
                            6
                    ).toString()
            );

            CadastroPaciente tela =
                    new CadastroPaciente(paciente);

            tela.setVisible(true);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao abrir paciente para alteração:\n"
                    + e.getMessage()
            );

            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

