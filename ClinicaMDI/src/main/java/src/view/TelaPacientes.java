    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    if (!validarCampos()) {
        return;
    }

    model.Paciente paciente = new model.Paciente();

    paciente.setNome(txtNome.getText().trim());
    paciente.setCpf(txtCpf.getText().trim());
    paciente.setDataNascimento(txtData.getText().trim()); 
    paciente.setTelefone(txtTelefone.getText().trim());
    paciente.setEmail(txtEmail.getText().trim());
    // Normaliza o convênio para maiúsculas (SO, LP, AMS, IP)
    paciente.setConvenio(txtConvenio.getText().trim().toUpperCase());

    repo.salvar(paciente);

    javax.swing.JOptionPane.showMessageDialog(this, "Paciente cadastrado com sucesso!");

    limparCampos();
    preencherTabela(); 



    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String textoCodigo = txtCodigo.getText().trim();

    if (textoCodigo.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite o código do paciente para buscar!");
        txtCodigo.requestFocus();
        return;
    }

    try {
        int codigo = Integer.parseInt(textoCodigo);
        Paciente p = repo.buscarPorCodigo(codigo); // Chama o método do repositório

        if (p != null) {
            // Preenche os campos do formulário com os dados retornados
            txtNome.setText(p.getNome());
            txtCpf.setText(p.getCpf());
            txtData.setText(p.getDataNascimento());
            txtTelefone.setText(p.getTelefone());
            txtEmail.setText(p.getEmail());
            txtConvenio.setText(p.getConvenio());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Paciente com código " + codigo + " não foi encontrado!");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, " O campo código deve conter apenas números inteiros!");
    }


    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
        if (txtCodigo.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe o código do paciente que deseja alterar!");
            txtCodigo.requestFocus();
            return;
        }

        if (!validarCampos()) {
            return; // Garante que os novos dados editados estejam no padrão
        }

        model.Paciente paciente = new model.Paciente();
        paciente.setCodigo(Integer.parseInt(txtCodigo.getText().trim()));
        paciente.setNome(txtNome.getText().trim());
        paciente.setCpf(txtCpf.getText().trim());
        paciente.setDataNascimento(txtData.getText().trim());
        paciente.setTelefone(txtTelefone.getText().trim());
        paciente.setEmail(txtEmail.getText().trim());
        paciente.setConvenio(txtConvenio.getText().trim());

        boolean sucesso = repo.alterar(paciente);

        if (sucesso) {
            javax.swing.JOptionPane.showMessageDialog(this, "Paciente alterado com sucesso!");
            limparCampos();
            preencherTabela();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Código não encontrado para alteração!");
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite um código numérico válido!");
    }
    
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        
    try {
        if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o código do paciente que deseja excluir!");
            return;
        }

        int codigo = Integer.parseInt(txtCodigo.getText().trim());

        int resposta = JOptionPane.showConfirmDialog(
            this, 
            "Confirma a exclusão do paciente código " + codigo + "?", 
            "Excluir Paciente", 
            JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {
            boolean removido = repo.excluirPorCodigo(codigo);

            if (removido) {
                JOptionPane.showMessageDialog(this, "Paciente excluído com sucesso!");
                limparCampos();     // Limpa todos os campos (inclusive o txtCodigo)
                preencherTabela();  // Atualiza a tabela na tela
            } else {
                JOptionPane.showMessageDialog(this, "Não foi encontrado paciente com o código " + codigo);
            }
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Digite apenas números no campo Código!");
    }  
    }//GEN-LAST:event_jButton4ActionPerformed

