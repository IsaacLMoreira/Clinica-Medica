public void preencherTabela() {
   
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) Tabela.getModel();

    model.setRowCount(0);

    java.util.List<model.Paciente> lista = repo.listarTodos();

    System.out.println(
            ">>> QUANTIDADE DE PACIENTES NO BANCO: " + lista.size()
    );

    for (model.Paciente p : lista) {

        model.addRow(new Object[]{
            p.getCodigo(),
            p.getNome(),
            p.getCpf(),
            p.getDataNascimento(),
            p.getTelefone(),
            p.getEmail(),
            p.getConvenio()
        });
    }
}
private void limparCampos() {
    txtCodigo.setText("");
    txtNome.setText("");
    txtCpf.setText("");
    txtData.setText("");
    txtTelefone.setText("");
    txtEmail.setText("");
    txtConvenio.setText("");
    
    txtCodigo.requestFocus();

}
private boolean validarCampos() {
    if (txtNome.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Informe o Nome do paciente!");
        txtNome.requestFocus();
        return false;
    }

    // CPF: exatamente 11 dígitos
    if (!txtCpf.getText().matches("\\d{11}")) {
        javax.swing.JOptionPane.showMessageDialog(this, "O CPF deve conter exatamente 11 números!");
        txtCpf.requestFocus();
        return false;
    }

    // Data de Nascimento: exatamente 8 dígitos
    if (!txtData.getText().matches("\\d{8}")) {
        javax.swing.JOptionPane.showMessageDialog(this, "A Data de Nascimento deve conter exatamente 8 números!");
        txtData.requestFocus();
        return false;
    }

    // Telefone: exatamente 11 dígitos
    if (!txtTelefone.getText().matches("\\d{11}")) {
        javax.swing.JOptionPane.showMessageDialog(this, "O Telefone deve conter exatamente 11 números!");
        txtTelefone.requestFocus();
        return false;
    }

    // E-mail: obrigatório terminar em @gmail.com
    if (!txtEmail.getText().trim().toLowerCase().endsWith("@gmail.com")) {
        javax.swing.JOptionPane.showMessageDialog(this, "O E-mail deve terminar com @gmail.com!");
        txtEmail.requestFocus();
        return false;
    }
    String convenio = txtConvenio.getText().trim().toLowerCase();

        if (!convenio.equals("so") && !convenio.equals("lp") && !convenio.equals("ams") && !convenio.equals("ip")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Convênio inválido! Permitidos apenas: SO, LP, AMS ou IP.");
        txtConvenio.requestFocus();
        return false;
}

    return true;
}
